fun computeUnifiedDiff(
    original: String,
    newContent: String,
    path: String,
): String {
    val origTrimmed = original.trimEnd('\n')
    val newTrimmed = newContent.trimEnd('\n')
    if (origTrimmed == newTrimmed) return ""
    val originalLines = if (original.isBlank()) emptyList() else original.lines()
    val newLines = if (newContent.isBlank()) emptyList() else newContent.lines()
    val patch =
        com.github.difflib.DiffUtils
            .diff(originalLines, newLines)
    val diff =
        com.github.difflib.UnifiedDiffUtils.generateUnifiedDiff(
            "a/$path",
            "b/$path",
            originalLines,
            patch,
            3,
        )
    return diff.joinToString("\n")
}

fun isTestFile(path: String): Boolean = path.contains("test", ignoreCase = true) || path.contains("spec", ignoreCase = true)

fun isRelatedToFile(
    testPath: String,
    filePath: String,
): Boolean {
    val baseName = filePath.substringAfterLast('/').substringBeforeLast('.')
    return testPath.contains(baseName, ignoreCase = true)
}

fun extensionToLanguage(path: String): String = SourceLanguages.of(path)

fun buildFixTicket(
    branchKey: String,
    finding: SecurityFinding,
    explanation: String,
) = JiraTicketData(
    key = branchKey,
    summary = "Security Fix: ${finding.description.take(72)}",
    description = "## Security Vulnerability\n\n${finding.description}\n\n## Fix Summary\n\n$explanation",
    comments = "",
    issueType = "Bug",
    status = "Open",
    priority =
        when {
            finding.severity == "CRITICAL" -> "Blocker"
            finding.severity == "HIGH" -> "High"
            finding.severity == "MEDIUM" -> "Medium"
            else -> "Low"
        },
    labels = listOfNotNull("security", "security-analysis", finding.cwe).filter { it.isNotBlank() },
    components = emptyList(),
    url = "",
    acceptanceCriteria =
        listOf(
            "Security vulnerability ${finding.cwe ?: finding.type} in ${finding.file} is fixed",
            "All existing tests still pass",
        ),
)

fun buildCodeImpl(
    repoName: String,
    finding: SecurityFinding,
    changes: List<ParsedFileChange>,
) = JiraCodeImplementation(
    identifiedRepositories = listOf(repoName),
    identifiedDatabases = emptyList(),
    files =
        changes.map { c ->
            JiraCodeFile(
                repository = repoName,
                path = c.path,
                language = extensionToLanguage(c.path),
                description = "Security fix for ${finding.cwe ?: finding.type}: ${finding.description.take(80)}",
                changeType = c.changeType,
                code = c.code,
            )
        },
    testFiles = emptyList(),
    systemTestFiles = emptyList(),
    databaseChanges = emptyList(),
    implementationNotes = "Security fix generated by StackLens Security Analysis (finding: ${finding.id})",
)

