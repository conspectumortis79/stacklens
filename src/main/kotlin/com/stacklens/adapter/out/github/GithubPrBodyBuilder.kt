package com.stacklens.adapter.out.github

import com.stacklens.application.port.out.JiraTicketData

class GithubPrBodyBuilder {
    fun build(ticket: JiraTicketData): String =
        buildString {
            appendLine("## ${ticket.key}: ${ticket.summary}")
            appendLine()
            appendLine("**Ticket:** ${ticket.url}")
            appendLine()
            if (ticket.description.isNotBlank()) {
                appendLine("### Description")
                appendLine(ticket.description)
                appendLine()
            }
            if (ticket.acceptanceCriteria.isNotEmpty()) {
                appendLine("### Acceptance Criteria")
                ticket.acceptanceCriteria.forEach { appendLine("- $it") }
                appendLine()
            }
            appendLine("---")
            appendLine("_Generated by StackLens_")
        }
}
