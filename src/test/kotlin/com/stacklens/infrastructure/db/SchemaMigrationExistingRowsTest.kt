package com.stacklens.infrastructure.db

import org.junit.jupiter.api.Assertions.assertDoesNotThrow
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertThrows
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test
import java.sql.Connection
import java.sql.DriverManager

class SchemaMigrationExistingRowsTest {
    @Test
    fun `ADD COLUMN without DEFAULT against existing rows is rejected by H2`() {
        withFreshTable { conn ->
            conn.createStatement().use { stmt ->
                stmt.execute("CREATE TABLE sample (id IDENTITY PRIMARY KEY, name VARCHAR(50) NOT NULL)")
                stmt.execute("INSERT INTO sample (name) VALUES ('pre-existing-1')")
                stmt.execute("INSERT INTO sample (name) VALUES ('pre-existing-2')")
                val rs = stmt.executeQuery("SELECT COUNT(*) FROM sample")
                rs.next()
                assertTrue(rs.getInt(1) == 2, "setup should have inserted 2 rows")
            }

            val ex =
                assertThrows(Exception::class.java) {
                    conn.createStatement().use { stmt ->
                        stmt.execute("ALTER TABLE sample ADD COLUMN consecutive_failures INTEGER NOT NULL")
                    }
                }
            assertTrue(
                ex.message?.contains("NULL") == true ||
                    ex.message?.contains("NOT NULL") == true ||
                    ex.cause?.message?.contains("NULL") == true,
                "expected NULL/NOT NULL violation, got: ${ex.message}",
            )
        }
    }

    @Test
    fun `ADD COLUMN INTEGER NOT NULL DEFAULT 0 works against existing rows`() {
        withFreshTable { conn ->
            conn.createStatement().use { stmt ->
                stmt.execute("CREATE TABLE sample (id IDENTITY PRIMARY KEY, name VARCHAR(50) NOT NULL)")
                stmt.execute("INSERT INTO sample (name) VALUES ('pre-existing-1')")
                stmt.execute("INSERT INTO sample (name) VALUES ('pre-existing-2')")
                assertDoesNotThrow {
                    stmt.execute("ALTER TABLE sample ADD COLUMN consecutive_failures INTEGER NOT NULL DEFAULT 0")
                }
                stmt.executeQuery("SELECT name, consecutive_failures FROM sample").use { rs ->
                    val seen = mutableListOf<Pair<String, Int>>()
                    while (rs.next()) {
                        seen += rs.getString("name") to rs.getInt("consecutive_failures")
                    }
                    assertTrue(seen.size == 2, "expected 2 rows, got ${seen.size}")
                    seen.forEach { (name, value) ->
                        assertTrue(value == 0, "row '$name' must have consecutive_failures=0 by DEFAULT")
                    }
                }
            }
        }
    }

    @Test
    fun `DROP COLUMN IF EXISTS is idempotent and works against an empty table`() {
        withFreshTable { conn ->
            conn.createStatement().use { stmt ->
                stmt.execute("CREATE TABLE sample (id IDENTITY PRIMARY KEY, name VARCHAR(50) NOT NULL)")
                assertDoesNotThrow {
                    stmt.execute("ALTER TABLE sample DROP COLUMN IF EXISTS leftover_column")
                }
                stmt.execute("ALTER TABLE sample ADD COLUMN leftover_column INTEGER")
                assertDoesNotThrow {
                    stmt.execute("ALTER TABLE sample DROP COLUMN IF EXISTS leftover_column")
                }
            }
        }
    }

    @Test
    fun `knowledge_sources type ENUM migration adds missing JIRA_SPRINT value`() {
        withFreshTable { conn ->
            conn.createStatement().use { stmt ->
                stmt.execute(
                    "CREATE TABLE knowledge_sources (" +
                        "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                        "type ENUM('CONFLUENCE', 'FILE', 'JIRA', 'MANUAL', " +
                        "'REVIEW_ANALYSIS', 'SPRINT_REVIEW', 'TICKET_CREATION', " +
                        "'TICKET_REFINEMENT', 'TICKET_SUMMARY') NOT NULL)",
                )
                val brokenInsert =
                    assertThrows(Exception::class.java) {
                        stmt.execute(
                            "INSERT INTO knowledge_sources (type) VALUES ('JIRA_SPRINT')",
                        )
                    }
                assertTrue(
                    brokenInsert.message?.contains("JIRA_SPRINT") == true ||
                        brokenInsert.cause?.message?.contains("JIRA_SPRINT") == true,
                    "expected the broken INSERT to be rejected with the JIRA_SPRINT " +
                        "enum-label error, got: ${brokenInsert.message}",
                )

                stmt.execute(
                    "ALTER TABLE knowledge_sources ALTER COLUMN type " +
                        "ENUM('CONFLUENCE', 'FILE', 'JIRA', 'JIRA_SPRINT', 'MANUAL', " +
                        "'REVIEW_ANALYSIS', 'SPRINT_REVIEW', 'TICKET_CREATION', " +
                        "'TICKET_REFINEMENT', 'TICKET_SUMMARY')",
                )

                assertDoesNotThrow {
                    stmt.execute(
                        "INSERT INTO knowledge_sources (type) VALUES ('JIRA_SPRINT')",
                    )
                }

                val expected =
                    setOf(
                        "CONFLUENCE",
                        "FILE",
                        "JIRA",
                        "JIRA_SPRINT",
                        "MANUAL",
                        "REVIEW_ANALYSIS",
                        "SPRINT_REVIEW",
                        "TICKET_CREATION",
                        "TICKET_REFINEMENT",
                        "TICKET_SUMMARY",
                    )
                stmt
                    .executeQuery(
                        "SELECT VALUE_NAME FROM INFORMATION_SCHEMA.ENUM_VALUES " +
                            "WHERE OBJECT_NAME = 'KNOWLEDGE_SOURCES'",
                    ).use { rs ->
                        val seen = mutableSetOf<String>()
                        while (rs.next()) {
                            val value = rs.getString(1)
                            if (value != null) seen.add(value)
                        }
                        assertTrue(
                            seen.containsAll(expected),
                            "missing enum labels after migration: ${expected - seen}",
                        )
                    }
            }
        }
    }

    @Test
    fun `ADD COLUMN include_linked_tickets with DEFAULT TRUE works against existing rows`() {
        withFreshTable { conn ->
            conn.createStatement().use { stmt ->
                stmt.execute(
                    "CREATE TABLE knowledge_sources (" +
                        "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                        "name VARCHAR(200) NOT NULL, " +
                        "type VARCHAR(40) NOT NULL, " +
                        "active BOOLEAN NOT NULL, " +
                        "include_children BOOLEAN NOT NULL DEFAULT FALSE, " +
                        "include_comments BOOLEAN NOT NULL DEFAULT FALSE, " +
                        "max_depth INTEGER NOT NULL DEFAULT 10, " +
                        "auto_managed BOOLEAN NOT NULL DEFAULT FALSE)",
                )
                stmt.execute("INSERT INTO knowledge_sources (name, type, active) VALUES ('legacy-1', 'JIRA', TRUE)")
                stmt.execute("INSERT INTO knowledge_sources (name, type, active) VALUES ('legacy-2', 'JIRA', TRUE)")
                assertDoesNotThrow {
                    stmt.execute(
                        "ALTER TABLE knowledge_sources ADD COLUMN include_linked_tickets BOOLEAN NOT NULL DEFAULT TRUE",
                    )
                }
                stmt.executeQuery("SELECT name, include_linked_tickets FROM knowledge_sources").use { rs ->
                    val seen = mutableListOf<Pair<String, Boolean>>()
                    while (rs.next()) {
                        seen += rs.getString(1) to rs.getBoolean(2)
                    }
                    assertEquals(2, seen.size, "expected 2 legacy rows to survive the migration")
                    seen.forEach { (name, value) ->
                        assertTrue(value, "row '$name' must have include_linked_tickets=true by DEFAULT")
                    }
                }
            }
        }
    }

    @Test
    fun `ADD COLUMN include_parent with DEFAULT TRUE works against existing rows`() {
        withFreshTable { conn ->
            conn.createStatement().use { stmt ->
                stmt.execute(
                    "CREATE TABLE knowledge_sources (" +
                        "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                        "name VARCHAR(200) NOT NULL, " +
                        "type VARCHAR(40) NOT NULL, " +
                        "active BOOLEAN NOT NULL)",
                )
                stmt.execute("INSERT INTO knowledge_sources (name, type, active) VALUES ('legacy', 'JIRA', TRUE)")
                assertDoesNotThrow {
                    stmt.execute(
                        "ALTER TABLE knowledge_sources ADD COLUMN include_parent BOOLEAN NOT NULL DEFAULT TRUE",
                    )
                }
                stmt.executeQuery("SELECT include_parent FROM knowledge_sources").use { rs ->
                    assertTrue(rs.next())
                    assertTrue(rs.getBoolean(1), "legacy row must default to include_parent=true")
                }
            }
        }
    }

    @Test
    fun `knowledge_documents source_type ENUM migration is idempotent on fresh schema`() {
        withFreshTable { conn ->
            conn.createStatement().use { stmt ->
                stmt.execute(
                    "CREATE TABLE knowledge_documents (" +
                        "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                        "source_type ENUM('CONFLUENCE', 'FILE', 'JIRA', 'JIRA_SPRINT', " +
                        "'MANUAL', 'REVIEW_ANALYSIS', 'SPRINT_REVIEW', " +
                        "'TICKET_CREATION', 'TICKET_REFINEMENT', 'TICKET_SUMMARY') NOT NULL)",
                )
                assertDoesNotThrow {
                    stmt.execute(
                        "ALTER TABLE knowledge_documents ALTER COLUMN source_type " +
                            "ENUM('CONFLUENCE', 'FILE', 'JIRA', 'JIRA_SPRINT', " +
                            "'MANUAL', 'REVIEW_ANALYSIS', 'SPRINT_REVIEW', " +
                            "'TICKET_CREATION', 'TICKET_REFINEMENT', 'TICKET_SUMMARY')",
                    )
                }
                stmt
                    .executeQuery(
                        "SELECT VALUE_NAME FROM INFORMATION_SCHEMA.ENUM_VALUES " +
                            "WHERE OBJECT_NAME = 'KNOWLEDGE_DOCUMENTS'",
                    ).use { rs ->
                        val seen = mutableSetOf<String>()
                        while (rs.next()) {
                            val v = rs.getString(1)
                            if (v != null) seen.add(v)
                        }
                        val missing =
                            setOf(
                                "CONFLUENCE",
                                "FILE",
                                "JIRA",
                                "JIRA_SPRINT",
                                "MANUAL",
                                "REVIEW_ANALYSIS",
                                "SPRINT_REVIEW",
                                "TICKET_CREATION",
                                "TICKET_REFINEMENT",
                                "TICKET_SUMMARY",
                            ).subtract(seen)
                        assertTrue(
                            missing.isEmpty(),
                            "labels disappeared after idempotent re-ALTER: $missing",
                        )
                    }
            }
        }
    }

    private inline fun withFreshTable(body: (Connection) -> Unit) {
        val url = "jdbc:h2:mem:schema-migration-${System.nanoTime()};DB_CLOSE_DELAY=-1"
        val conn = DriverManager.getConnection(url, "sa", "")
        try {
            body(conn)
        } finally {
            conn.close()
        }
    }
}
