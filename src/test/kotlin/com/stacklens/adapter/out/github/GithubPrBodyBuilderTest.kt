package com.stacklens.adapter.out.github

import com.stacklens.application.port.out.JiraTicketData
import org.junit.jupiter.api.Assertions.assertFalse
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test

class GithubPrBodyBuilderTest {
    private val builder = GithubPrBodyBuilder()

    private fun ticket(
        key: String = "PROJ-1",
        summary: String = "Add feature",
        url: String = "https://jira/PROJ-1",
        description: String = "",
        acceptanceCriteria: List<String> = emptyList(),
    ) = JiraTicketData(
        key = key,
        summary = summary,
        description = description,
        comments = "",
        issueType = "Story",
        status = "Open",
        priority = null,
        labels = emptyList(),
        components = emptyList(),
        url = url,
        acceptanceCriteria = acceptanceCriteria,
    )

    @Test
    fun `build includes header with key and summary`() {
        val body = builder.build(ticket(key = "PROJ-7", summary = "Login fix"))
        assertTrue(body.contains("## PROJ-7: Login fix"))
    }

    @Test
    fun `build includes ticket URL`() {
        val body = builder.build(ticket(url = "https://jira.example.com/PROJ-1"))
        assertTrue(body.contains("**Ticket:** https://jira.example.com/PROJ-1"))
    }

    @Test
    fun `build omits description section when description is blank`() {
        val body = builder.build(ticket(description = ""))
        assertFalse(body.contains("### Description"))
    }

    @Test
    fun `build includes description section when description is non-blank`() {
        val body = builder.build(ticket(description = "Long description"))
        assertTrue(body.contains("### Description"))
        assertTrue(body.contains("Long description"))
    }

    @Test
    fun `build omits acceptance criteria section when list is empty`() {
        val body = builder.build(ticket(acceptanceCriteria = emptyList()))
        assertFalse(body.contains("### Acceptance Criteria"))
    }

    @Test
    fun `build includes acceptance criteria list when non-empty`() {
        val body = builder.build(ticket(acceptanceCriteria = listOf("works on Chrome", "no console errors")))
        assertTrue(body.contains("### Acceptance Criteria"))
        assertTrue(body.contains("- works on Chrome"))
        assertTrue(body.contains("- no console errors"))
    }

    @Test
    fun `build includes footer`() {
        val body = builder.build(ticket())
        assertTrue(body.contains("---"))
        assertTrue(body.contains("_Generated by StackLens_"))
    }

    @Test
    fun `build with all sections produces a coherent body`() {
        val body =
            builder.build(
                ticket(
                    key = "PROJ-9",
                    summary = "Big change",
                    url = "https://jira/PROJ-9",
                    description = "Lots of details",
                    acceptanceCriteria = listOf("AC1", "AC2"),
                ),
            )
        assertTrue(body.contains("## PROJ-9: Big change"))
        assertTrue(body.contains("### Description"))
        assertTrue(body.contains("Lots of details"))
        assertTrue(body.contains("### Acceptance Criteria"))
        assertTrue(body.contains("- AC1"))
        assertTrue(body.contains("- AC2"))
        assertTrue(body.contains("_Generated by StackLens_"))
    }
}
